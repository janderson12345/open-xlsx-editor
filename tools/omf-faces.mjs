// Writes src/editor/omf.js from an open-metric-fonts morrow-sans package (npm's @open-metric-fonts/morrow-sans, or the
// release web bundle's morrow-sans folder): the faces of Morrow Sans Narrow (Aptos Narrow's twin) and Morrow Sans
// (Aptos's) the editor loads, regular, italic, bold and bold italic, each alphabet's file and unicode-range as the
// package's own index.css gives them. Numbers and names only; no font is copied.
// usage: node tools/omf-faces.mjs <morrow-sans package folder>
import fs from 'node:fs';
import path from 'node:path';

const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/omf-faces.mjs <morrow-sans package folder>'); process.exit(2); }
const { version } = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
const css = fs.readFileSync(path.join(dir, 'index.css'), 'utf8');
const faces = [];
for (const [, body] of css.matchAll(/@font-face \{([^}]*)\}/g)) {
  const get = (re) => re.exec(body)?.[1];
  const family = get(/font-family: '([^']*)'/);
  const weight = Number(get(/font-weight: (\d+)/));
  const style = get(/font-style: (\w+)/);
  const file = get(/url\(\.\/files\/([^)]*)\)/);
  const range = get(/unicode-range: ([^;]*);/)?.replace(/\s+/g, '');
  if (!['Morrow Sans', 'Morrow Sans Narrow'].includes(family) || ![400, 700].includes(weight) || !file || !range) continue;
  faces.push({ family, weight, style, file, range });
}
const out = `// Generated by tools/omf-faces.mjs from open-metric-fonts' morrow-sans ${version}: the faces fonts.js's metric twins
// are loaded from (omffonts.js), each alphabet's file under <omf folder>/morrow-sans/files/ and its unicode-range.
// Don't edit: run the script again on a newer package.

export const OMF_VERSION = '${version}';

/** [family, weight, style, file, unicode-range]. */
export const OMF_FACES = [
${faces.map((f) => `  [${JSON.stringify(f.family)}, ${f.weight}, '${f.style}', '${f.file}', '${f.range}'],`).join('\n')}
];
`;
fs.writeFileSync('src/editor/omf.js', out);
console.log(`src/editor/omf.js: ${faces.length} faces from morrow-sans ${version}`);
