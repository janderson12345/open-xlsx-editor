// Writes src/ooxml/excelwidths.js from gdi-charwidths.ps1's measurement: for each font, regular and bold, the whole-
// pixel width Windows gives each printable ASCII character (32 to 126) at each pixel size from 11 to 48 (8 to 36pt;
// half points that round to one pixel size have one set of widths, checked here), and Small Fonts' at 5 to 10px,
// which Excel lays every font out in under 8pt. One string a font and weight, character by character, a width w as
// the character 48 + w.
// usage: node tools/excel-compare/charwidths-table.mjs <gdi-charwidths.json>
import fs from 'node:fs';

const FIRST = 32;
const LAST = 126;
const PX_FROM = 11;
const PX_TO = 48;
const SMALL_FROM = 5;
const SMALL_TO = 10;
const data = JSON.parse(fs.readFileSync(process.argv[2], 'utf8').trimStart());
const pack = (byPx, from, to, what) => {
  let s = '';
  for (let ch = FIRST; ch <= LAST; ch++) {
    for (let px = from; px <= to; px++) {
      const w = byPx.get(px)?.[ch - 32];
      if (w == null || w < 0 || 48 + w > 0xffff) throw new Error(`${what} ${px}px: no width for ${ch}`);
      s += String.fromCharCode(48 + w);
    }
  }
  return s;
};
const lines = [];
let small = null;
for (const [font, entry] of Object.entries(data)) {
  if (font === 'small fonts') { small = pack(new Map(Object.entries(entry.px).map(([px, w]) => [Number(px), w])), SMALL_FROM, SMALL_TO, font); continue; }
  const weights = {};
  for (const weight of ['regular', 'bold']) {
    const byPx = new Map();
    for (const [pt, widths] of Object.entries(entry[weight])) {
      const px = Math.round((Number(pt) * 4) / 3);
      if (byPx.has(px) && byPx.get(px).join() !== widths.join()) throw new Error(`${font} ${weight}: ${pt}pt differs from another size of ${px}px`);
      byPx.set(px, widths);
    }
    weights[weight] = pack(byPx, PX_FROM, PX_TO, `${font} ${weight}`);
  }
  lines.push(`  ${JSON.stringify(font)}: { regular: ${JSON.stringify(weights.regular)}, bold: ${JSON.stringify(weights.bold)} },`);
}
if (!small) throw new Error('no "small fonts" in the measurement');
const out = `// Generated by tools/excel-compare/charwidths-table.mjs from tools/excel-compare/gdi-charwidths.ps1's measurement:
// the width in whole pixels Windows (GDI) gives each printable ASCII character of each font, regular and bold, at
// each pixel size from ${PX_FROM} to ${PX_TO} (8 to 36pt), as Excel lays text out on screen, and of Small Fonts at ${SMALL_FROM} to ${SMALL_TO}px,
// the bitmap font Excel lays every font out in under 8pt. Excel breaks wrapped lines at the sum of these
// (editor/rowheights.js); the browser's fractional widths miss it by a varying few percent. Don't edit: measure
// again and run the script.

const PX_FROM = ${PX_FROM};
const PX_TO = ${PX_TO};
const SMALL_FROM = ${SMALL_FROM};
const SMALL_TO = ${SMALL_TO};
const FIRST = ${FIRST};
const LAST = ${LAST};

/** Font (lower case) -> { regular, bold }: per character (${FIRST} to ${LAST}), its width at each pixel size, as the character
 *  48 + width. */
const WIDTHS = {
${lines.join('\n')}
};

/** Small Fonts, regular: per character, its width at ${SMALL_FROM} to ${SMALL_TO}px. */
const SMALL = ${JSON.stringify(small)};

/** Excel's character widths for font \`name\` at \`px\` pixels (its size in points x 4/3), regular or bold:
 *  { width(code), digit, small }, or null when the table hasn't the font or the size. \`width(code)\` is a
 *  character's whole pixels, -1 for one outside printable ASCII; \`digit\` the width of 0. Sizes that round to ${SMALL_TO}px
 *  or less are Small Fonts' whatever the font (\`small\`: its bold is each regular width and one pixel, as Windows
 *  makes a bold of a bitmap font). */
export function excelWidths(name, px, bold) {
  const size = Math.round(px);
  let s;
  let n;
  let at;
  let add = 0;
  if (size <= SMALL_TO) {
    s = SMALL;
    n = SMALL_TO - SMALL_FROM + 1;
    at = Math.max(SMALL_FROM, size) - SMALL_FROM;
    add = bold ? 1 : 0;
  } else {
    const table = WIDTHS[String(name).toLowerCase()];
    if (!table || size > PX_TO) return null;
    s = bold ? table.bold : table.regular;
    n = PX_TO - PX_FROM + 1;
    at = size - PX_FROM;
  }
  const width = (code) => (code >= FIRST && code <= LAST ? s.charCodeAt((code - FIRST) * n + at) - 48 + add : -1);
  return { width, digit: width(48), small: size <= SMALL_TO };
}
`;
fs.writeFileSync('src/ooxml/excelwidths.js', out);
console.log(`${lines.length} fonts, ${out.length} characters`);
