// Writes src/ooxml/excelwidths.js from gdi-charwidths.ps1's measurement: for each font, regular and bold, the whole-
// pixel width Windows gives each printable ASCII character (32 to 126) at each pixel size from 8 to 48 (6 to 36pt;
// half points that round to one pixel size have one set of widths, checked here). One string a font and weight,
// character by character, 41 sizes each, a width w as the character 48 + w.
// Not in use: wrapping at these widths was tried and set aside (docs/LAYOUT.md, Tried and dropped).
// usage: node tools/excel-compare/charwidths-table.mjs <gdi-charwidths.json>
import fs from 'node:fs';

const FIRST = 32;
const LAST = 126;
const PX_FROM = 8;
const PX_TO = 48;
const data = JSON.parse(fs.readFileSync(process.argv[2], 'utf8').trimStart());
const lines = [];
for (const [font, entry] of Object.entries(data)) {
  const weights = {};
  for (const weight of ['regular', 'bold']) {
    const byPx = new Map();
    for (const [pt, widths] of Object.entries(entry[weight])) {
      const px = Math.round((Number(pt) * 4) / 3);
      if (byPx.has(px) && byPx.get(px).join() !== widths.join()) throw new Error(`${font} ${weight}: ${pt}pt differs from another size of ${px}px`);
      byPx.set(px, widths);
    }
    let s = '';
    for (let ch = FIRST; ch <= LAST; ch++) {
      for (let px = PX_FROM; px <= PX_TO; px++) {
        const w = byPx.get(px)?.[ch - 32];
        if (w == null || w < 0 || 48 + w > 0xffff) throw new Error(`${font} ${weight} ${px}px: no width for ${ch}`);
        s += String.fromCharCode(48 + w);
      }
    }
    weights[weight] = s;
  }
  lines.push(`  ${JSON.stringify(font)}: { regular: ${JSON.stringify(weights.regular)}, bold: ${JSON.stringify(weights.bold)} },`);
}
const out = `// Generated by tools/excel-compare/charwidths-table.mjs from tools/excel-compare/gdi-charwidths.ps1's measurement:
// the width in whole pixels Windows (GDI) gives each printable ASCII character of each font, regular and bold, at
// each pixel size from ${PX_FROM} to ${PX_TO} (6 to 36pt), as Excel lays text out on screen. Excel breaks wrapped lines
// at the sum of these; the browser's fractional widths miss it by a varying few percent (rowheights.js). Don't edit:
// measure again and run the script.

export const WIDTH_PX_FROM = ${PX_FROM};
export const WIDTH_PX_TO = ${PX_TO};
const FIRST = ${FIRST};
const LAST = ${LAST};
const SIZES = WIDTH_PX_TO - WIDTH_PX_FROM + 1;

/** Font (lower case) -> { regular, bold }: per character (${FIRST} to ${LAST}), its width at each pixel size, as the character
 *  48 + width. */
const WIDTHS = {
${lines.join('\n')}
};

/** The width in pixels Windows gives \`text\` in font \`name\` at \`px\` pixels (a whole number), regular or bold: the sum
 *  of its characters' widths, \`other(ch)\` for a character the table hasn't (outside printable ASCII). Null when the
 *  font or size isn't in the table. */
export function gdiTextWidth(name, px, bold, text, other) {
  const table = WIDTHS[String(name).toLowerCase()];
  if (!table || !Number.isInteger(px) || px < WIDTH_PX_FROM || px > WIDTH_PX_TO) return null;
  const s = bold ? table.bold : table.regular;
  const at = px - WIDTH_PX_FROM;
  let w = 0;
  for (const ch of text) {
    const code = ch.charCodeAt(0);
    w += code >= FIRST && code <= LAST && ch.length === 1 ? s.charCodeAt((code - FIRST) * SIZES + at) - 48 : other(ch);
  }
  return w;
}
`;
fs.writeFileSync('src/ooxml/excelwidths.js', out);
console.log(`${lines.length} fonts, ${out.length} characters`);
