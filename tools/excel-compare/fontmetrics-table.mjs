// Writes src/ooxml/excelfonts.js from test/fontmetrics-excel.json (excel-fontmetrics.ps1): for each font measured,
// Excel's row height in pixels, regular and bold, and its maximum digit width in pixels, at each half point from 6pt
// to 36pt. Don't edit the output: measure again and run this.
// usage: node tools/excel-compare/fontmetrics-table.mjs
import fs from 'node:fs';

const j = JSON.parse(fs.readFileSync('test/fontmetrics-excel.json', 'utf8').trimStart());
const FROM = 6;
const TO = 36;
const px = (pt) => (pt == null ? 0 : Math.round(pt / 0.75));
const lines = [];
for (const [name, v] of Object.entries(j.fonts)) {
  const row = [];
  const bold = [];
  const mdw = [];
  for (let s = FROM; s <= TO; s += 0.5) {
    const x = v.sizes[String(s)];
    row.push(px(x?.[0]));
    bold.push(px(x?.[1]));
    // (A ninth of the 10-character column's pixels less the 1-character one's.)
    mdw.push(x ? Math.round((x[3] - x[2]) / 0.75 / 9) : 0);
  }
  lines.push(`  ${JSON.stringify(name.toLowerCase())}: { row: [${row}], bold: [${bold}], mdw: [${mdw}] },`);
}
const out = `// Generated by tools/excel-compare/fontmetrics-table.mjs from test/fontmetrics-excel.json (excel-fontmetrics.ps1,
// Excel ${j.excel} over COM): Excel's own row height and maximum digit width for each font measured, at each half point
// from ${FROM}pt to ${TO}pt (index (size - ${FROM}) * 2). Excel gets them from Windows' rendering of the font at the size in
// whole pixels, which no formula of the font's metrics gives: fonts.js fontRowPx and digitwidth.js digitWidth look
// here first. Don't edit: measure again and run the script.

export const EXCEL_FONT_FROM = ${FROM};
export const EXCEL_FONT_TO = ${TO};

/** Font (lower case) -> { row: px, bold: px (a bold Normal style's row), mdw: px }, each by half point; 0: none. */
export const EXCEL_FONTS = {
${lines.join('\n')}
};

/** The measured entry \`key\` ('row', 'bold' or 'mdw') of font \`name\` at \`pt\` (to the nearest half point), or null. */
export function excelFontMetric(name, pt, key) {
  const f = EXCEL_FONTS[String(name || '').toLowerCase()];
  if (!f || !(pt >= EXCEL_FONT_FROM && pt <= EXCEL_FONT_TO)) return null;
  const v = f[key][Math.round((pt - EXCEL_FONT_FROM) * 2)];
  return v || null;
}
`;
fs.writeFileSync('src/ooxml/excelfonts.js', out);
console.log(`src/ooxml/excelfonts.js: ${Object.keys(j.fonts).length} fonts`);
