// Writes src/ooxml/excelfonts.js from test/fontmetrics-excel.json (excel-fontmetrics.ps1) and test/fontlines-excel.json
// (excel-wraprows.ps1, wraprows-table.mjs): for each font measured, Excel's row height in pixels, regular and bold,
// its maximum digit width in pixels and its descent in pixels, at each half point from 6pt to 36pt; an italic's row
// and descent where they aren't the upright font's. Don't edit the output: measure again and run this.
// usage: node tools/excel-compare/fontmetrics-table.mjs
import fs from 'node:fs';

const j = JSON.parse(fs.readFileSync('test/fontmetrics-excel.json', 'utf8').trimStart());
const lineData = JSON.parse(fs.readFileSync('test/fontlines-excel.json', 'utf8').trimStart());
const FROM = 6;
const TO = 36;
const px = (pt) => (pt == null ? 0 : Math.round(pt / 0.75));
const lines = [];
let italics = 0;
for (const [name, v] of Object.entries(j.fonts)) {
  const row = [];
  const bold = [];
  const mdw = [];
  for (let s = FROM; s <= TO; s += 0.5) {
    const x = v.sizes[String(s)];
    row.push(px(x?.[0]));
    bold.push(px(x?.[1]));
    // (A ninth of the 10-character column's pixels less the 1-character one's.)
    mdw.push(x ? Math.round((x[3] - x[2]) / 0.75 / 9) : 0);
  }
  const l = lineData.fonts[name];
  if (!l) throw new Error(`${name}: no lines measured (test/fontlines-excel.json)`);
  // (The line a row of several lines is made of is the row of one, measured apart: checked.)
  l.regular.forEach(([line], k) => { if (row[k] && line !== row[k]) throw new Error(`${name} ${FROM + k / 2}pt: line ${line}px, row ${row[k]}px`); });
  l.bold.forEach(([line], k) => { if (bold[k] && line !== bold[k]) throw new Error(`${name} bold ${FROM + k / 2}pt: line ${line}px, row ${bold[k]}px`); });
  const col = (style, at) => l[style].map((x) => x[at]);
  let more = '';
  if (JSON.stringify(l.italic) !== JSON.stringify(l.regular) || JSON.stringify(l.boldItalic) !== JSON.stringify(l.bold)) {
    italics++;
    more = `, italic: [${col('italic', 0)}], italicDesc: [${col('italic', 1)}], boldItalic: [${col('boldItalic', 0)}], boldItalicDesc: [${col('boldItalic', 1)}]`;
  }
  lines.push(`  ${JSON.stringify(name.toLowerCase())}: { row: [${row}], bold: [${bold}], mdw: [${mdw}], desc: [${col('regular', 1)}], boldDesc: [${col('bold', 1)}]${more} },`);
}
const out = `// Generated by tools/excel-compare/fontmetrics-table.mjs from test/fontmetrics-excel.json (excel-fontmetrics.ps1,
// Excel ${j.excel} over COM) and test/fontlines-excel.json (excel-wraprows.ps1): Excel's own row height, maximum digit
// width and descent for each font measured, at each half point from ${FROM}pt to ${TO}pt (index (size - ${FROM}) * 2). Excel gets
// them from Windows' rendering of the font at the size in whole pixels, which no formula of the font's metrics
// gives: fonts.js fontRowPx and digitwidth.js digitWidth look here first. Don't edit: measure again and run the
// script.

export const EXCEL_FONT_FROM = ${FROM};
export const EXCEL_FONT_TO = ${TO};

/** Font (lower case) -> { row: px, bold: px (a bold font's row), mdw: px, desc: px (the descent a row counts,
 *  rowheights.js), boldDesc: px }, each by half point; 0: none. A font whose italic isn't as tall or as deep as its
 *  upright has italic, italicDesc, boldItalic and boldItalicDesc too (${italics} of them). */
export const EXCEL_FONTS = {
${lines.join('\n')}
};

/** The measured entry \`key\` ('row', 'bold' or 'mdw') of font \`name\` at \`pt\` (to the nearest half point), or null. */
export function excelFontMetric(name, pt, key) {
  const f = EXCEL_FONTS[String(name || '').toLowerCase()];
  if (!f || !(pt >= EXCEL_FONT_FROM && pt <= EXCEL_FONT_TO)) return null;
  const v = f[key][Math.round((pt - EXCEL_FONT_FROM) * 2)];
  return v || null;
}

/** Font \`name\`'s line at \`pt\`, bold or italic or both: { row, desc } in pixels, the height of a row of it and the
 *  descent Excel counts for it, or null when it isn't measured. */
export function excelFontLine(name, pt, bold, italic) {
  const f = EXCEL_FONTS[String(name || '').toLowerCase()];
  if (!f || !(pt >= EXCEL_FONT_FROM && pt <= EXCEL_FONT_TO)) return null;
  const at = Math.round((pt - EXCEL_FONT_FROM) * 2);
  const rows = (italic && (bold ? f.boldItalic : f.italic)) || (bold ? f.bold : f.row);
  const descs = (italic && (bold ? f.boldItalicDesc : f.italicDesc)) || (bold ? f.boldDesc : f.desc);
  return rows[at] ? { row: rows[at], desc: descs[at] } : null;
}
`;
fs.writeFileSync('src/ooxml/excelfonts.js', out);
console.log(`src/ooxml/excelfonts.js: ${Object.keys(j.fonts).length} fonts, ${italics} with an italic of its own height`);
